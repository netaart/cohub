import "./fixtures/native-home.js";
import assert from "node:assert/strict";
import test from "node:test";
import { nativeUserContent } from "@neta-art/cohub";
import { NativeRuntime } from "../src/runtime/native/daemon.js";
const settle = async () => { for (let i = 0; i < 4; i++) await new Promise<void>(resolve => setImmediate(resolve)); };
const message = (text: string) => ({ content: [{ type: "text" as const, text }], provider: null, model: null });
test("shared Codex switches to the complete transcript after steering and never overwrites it with partial shared deltas", async context => {
  context.mock.timers.enable({ apis: ["setTimeout"] });
  const runtime: any = new NativeRuntime({ spaceId: "space", root: "/project", stateRoot: "/unused", harnesses: [], executables: {}, identity: "test", config: null, archives: {} as never, projectionSource: {} as never, diagnostics: { log: () => {} } as never });
  const state = { path: "/project/shared.jsonl", harness: "codex", nativeSessionId: "native", sessionId: "session", runningTurnId: "cloud", runningTurnKey: "turn" };
  runtime.ingest.alive = () => {};
  runtime.ingest.running = () => state;
  runtime.watched.set("native", { path: state.path });
  const sent: any[] = [];
  runtime.send = async (event: any) => { sent.push(event.progress); return { accepted: true }; };
  context.after(() => { runtime.endFilePreview(state.path); runtime.endStream("codex:native"); });
  const event = (method: string, params: object) => runtime.onCodexEvent({ method, params: { threadId: "native", ...params } });
  event("item/started", { item: { type: "agentMessage", id: "assistant", text: "Original" } });
  event("item/agentMessage/delta", { itemId: "assistant", delta: "Original" });
  context.mock.timers.tick(250); await settle();
  assert.equal(sent.length, 1);
  const messages = [message("Original"), { ...message("Correction"), content: nativeUserContent(message("Correction").content) }, message("Updated")];
  runtime.onGrowth(state, { key: "turn", messages });
  context.mock.timers.tick(250); await settle();
  assert.deepEqual(sent.at(-1).messages, messages, "The full timeline must replace the assistant-only preview");
  assert.equal(runtime.streams.has("codex:native"), false);
  const count = sent.length;
  event("item/agentMessage/delta", { itemId: "assistant", delta: "Stale delta" });
  context.mock.timers.tick(1000); await settle();
  assert.equal(sent.length, count, "Shared events cannot overwrite the complete timeline");
  event("turn/started", { turn: { id: "next" } });
  assert.equal(runtime.filePreviews.has(state.path), false, "The next turn starts with normal streaming again");
  event("item/started", { item: { type: "agentMessage", id: "next-answer", text: "" } });
  event("item/agentMessage/delta", { itemId: "next-answer", delta: "Next turn" });
  context.mock.timers.tick(250); await settle();
  assert.deepEqual(sent.at(-1).messages, [message("Next turn")]);
});
