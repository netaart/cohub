type Value = string | number | readonly string[];
type Group = { name: string; plural?: string; kotlin?: string; entries: [wire: string, value: Value][] };
const plural = (group: Group) => group.plural ?? `${group.name}s`;

const groups = (): { constants: [string, Value][]; groups: Group[] } => {
  const apps = NATIVE_APPS;
  const names = (list: readonly string[]): [string, Value][] => list.map((name) => [name, name]);
  return {
    constants: [
      ["version", HOST_BRIDGE_VERSION],
      ["global", HOST_BRIDGE_GLOBAL],
      ["serviceVersion", HOST_SERVICE_VERSION],
      ["shareFileMaxBytes", HOST_SHARE_FILE_MAX_BYTES],
      ["shareScheme", HOST_SHARE_SCHEME],
      ["sharePath", HOST_SHARE_PATH],
      ["workspaceScheme", HOST_WORKSPACE_SCHEME],
      ["workspacePath", HOST_WORKSPACE_PATH],
      ["fileFrameMagic", HOST_FILE_FRAME_MAGIC],
      ["fileFrameHeaderBytes", HOST_FILE_FRAME_HEADER_BYTES],
      ["fileStreamMaxBytes", HOST_FILE_STREAM_MAX_BYTES],
      ["appleTeamId", apps.appleTeamId],
      ["authCallbackPath", apps.paths.authCallback],
      ["oneShotPaths", apps.paths.oneShot],
      ["landingPaths", apps.paths.landing],
      ["browserOnlyPaths", apps.paths.browserOnly],
      ["externalSchemes", apps.externalSchemes],
    ],
    groups: [
      { name: "Capability", plural: "Capabilities", entries: names(HOST_BRIDGE_CAPABILITIES) },
      { name: "Method", entries: names(Object.keys(HOST_BRIDGE_METHODS)) },
      { name: "Event", entries: names(HOST_BRIDGE_EVENTS) },
      { name: "ErrorCode", kotlin: "Errors", entries: names(Object.values(HOST_BRIDGE_ERROR)) },
      { name: "ServiceMethod", entries: names([HOST_SERVICE_WORKSPACE_ENDPOINT, HOST_SERVICE_CLI_ABOUT]) },
      { name: "ShellEvent", entries: Object.entries(HOST_SERVICE_SHELL_EVENTS) },
      { name: "Locale", entries: names(HOST_LOCALES) },
      { name: "SignInProvider", entries: names(HOST_SIGN_IN_PROVIDERS) },
      { name: "AuthFlowOutcome", entries: names(HOST_AUTH_FLOW_OUTCOMES) },
    ],
  };
};

const words = (wire: string) => (wire.match(/[A-Z]+(?![a-z])|[A-Z]?[a-z0-9]+/g) ?? []).map((word) => word.toLowerCase());
const camel = (wire: string) => words(wire).map((word, index) => (index ? word.charAt(0).toUpperCase() + word.slice(1) : word)).join("");
const pascal = (wire: string) => words(wire).map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("");
const screaming = (wire: string) => words(wire).join("_").toUpperCase();

const HEADER = "Generated by `pnpm --filter @cohub/protocol generate:host-bridge` from packages/protocol; do not edit.";

const literal = (value: Value, list: (items: string[]) => string) =>
  typeof value === "number" ? String(value) : typeof value === "string" ? JSON.stringify(value) : list(value.map((item) => JSON.stringify(item)));

export const swiftSource = () => {
  const { constants, groups: all } = groups();
  const lines = [`// ${HEADER}`, "// swift-format-ignore-file", "", "public enum HostProtocol {"];
  for (const [name, value] of constants) lines.push(`    public static let ${name} = ${literal(value, (items) => `[${items.join(", ")}]`)}`);
  for (const group of all) {
    lines.push("", `    public enum ${group.name} {`);
    for (const [wire, value] of group.entries) lines.push(`        public static let ${camel(wire)} = ${literal(value, String)}`);
    lines.push("    }");
  }
  lines.push("}", "");
  return lines.join("\n");
};

export const kotlinSource = () => {
  const { constants, groups: all } = groups();
  const lines = [`// ${HEADER}`, '@file:Suppress("ktlint")', "", "package live.cohub.android.host", "", "object HostProtocol {"];
  for (const [name, value] of constants) {
    const rendered = literal(value, (items) => `listOf(${items.join(", ")})`);
    lines.push(`    ${Array.isArray(value) ? "val" : "const val"} ${screaming(name)} = ${typeof value === "number" && value > 0x7fff_ffff ? `${value}L` : rendered}`);
  }
  for (const group of all) {
    lines.push("", `    object ${group.kotlin ?? plural(group)} {`);
    for (const [wire, value] of group.entries) lines.push(`        const val ${screaming(wire)} = ${literal(value, String)}`);
    lines.push("    }");
  }
  lines.push("}", "");
  return lines.join("\n");
};

export const csharpSource = () => {
  const { constants, groups: all } = groups();
  const lines = [`// ${HEADER}`, "", "namespace Cohub.Core;", "", "public static partial class HostProtocol", "{"];
  for (const [name, value] of constants) {
    if (Array.isArray(value)) lines.push(`    public static readonly string[] ${pascal(name)} = [${value.map((item) => JSON.stringify(item)).join(", ")}];`);
    else lines.push(`    public const ${typeof value === "number" ? (value > 0x7fff_ffff ? "long" : "int") : "string"} ${pascal(name)} = ${literal(value, String)};`);
  }
  for (const group of all) {
    lines.push("", `    public static class ${plural(group)}`, "    {");
    for (const [wire, value] of group.entries) lines.push(`        public const string ${pascal(wire)} = ${literal(value, String)};`);
    lines.push("    }");
  }
  lines.push("}", "");
  return lines.join("\n");
};

const xcconfigUrl = (url: string) => url.replace("://", ":/$()/");

export const xcconfigSource = (env: string) => {
  const apps = NATIVE_APPS;
  const deployment = apps.deployments[env];
  if (!deployment) throw new Error(`Unknown deployment ${env}`);
  return [
    `// ${HEADER}`,
    `COHUB_ENV = ${env}`,
    `COHUB_APP_NAME = ${deployment.appName}`,
    `COHUB_BUNDLE_ID = ${deployment.ios.bundleId}`,
    `COHUB_URL_SCHEME = ${deployment.urlScheme}`,
    `COHUB_WEB_HOST = ${new URL(deployment.webOrigin).host}`,
    `COHUB_API_ORIGIN = ${xcconfigUrl(deployment.apiOrigin)}`,
    `COHUB_LOGTO_ENDPOINT = ${xcconfigUrl(deployment.logtoEndpoint)}`,
    `COHUB_LOGTO_APP_ID = ${deployment.logtoAppId}`,
    "",
    '#include "Shared.xcconfig"',
    "",
  ].join("\n");
};

