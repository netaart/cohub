/** Generates the SDK's built-in Board themes from the Web theme stylesheets. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { color as parseColor } from "@csstools/css-color-parser";
import { parseComponentValue } from "@csstools/css-parser-algorithms";
import { tokenize } from "@csstools/css-tokenizer";
import postcss, { type Container } from "postcss";
import {
	type BoardThemeTokenSource,
	readBoardThemeColors,
	readBoardThemeStyle,
} from "../src/lib/board/board-theme-tokens.ts";
import { isDarkTheme, RESOLVED_THEMES } from "../src/lib/theme-registry.ts";

const here = dirname(fileURLToPath(import.meta.url));
const STYLESHEET = resolve(here, "../src/styles/theme.css");
export const GENERATED = resolve(
	here,
	"../../../packages/sdk/src/board/model/themes.ts",
);
const HEADER =
	"// Code generated by apps/web/scripts/board-themes.ts from the Web theme stylesheets; DO NOT EDIT.";

type Declaration = {
	value: string;
	layered: boolean;
	specificity: number;
	order: number;
};

function rootProperties(theme: string): Map<string, string> {
	const winners = new Map<string, Declaration>();
	let order = 0;
	const declare = (
		container: Container,
		layered: boolean,
		specificity: number,
	) => {
		container.each((node) => {
			if (node.type !== "decl" || !node.prop.startsWith("--")) return;
			const next = { value: node.value, layered, specificity, order: order++ };
			const current = winners.get(node.prop);
			if (!current || outranks(next, current)) winners.set(node.prop, next);
		});
	};
	const walk = (container: Container, file: string, layered: boolean) => {
		container.each((node) => {
			if (node.type === "rule") {
				const specificity = selectorList(node.selector, theme);
				if (specificity !== null) declare(node, layered, specificity);
			} else if (node.type === "atrule") {
				if (node.name === "import") {
					const path = resolve(
						dirname(file),
						node.params.replace(/^["']|["']$/g, ""),
					);
					walk(postcss.parse(readFileSync(path, "utf8")), path, layered);
				} else if (node.name === "layer") walk(node, file, true);
				else if (node.name === "theme") declare(node, true, 100);
			}
		});
	};
	walk(postcss.parse(readFileSync(STYLESHEET, "utf8")), STYLESHEET, false);
	return new Map([...winners].map(([name, { value }]) => [name, value]));
}

function outranks(next: Declaration, current: Declaration): boolean {
	if (next.layered !== current.layered) return !next.layered;
	if (next.specificity !== current.specificity)
		return next.specificity > current.specificity;
	return next.order > current.order;
}

function selectorList(list: string, theme: string): number | null {
	let best: number | null = null;
	for (const selector of splitTopLevel(list, ",")) {
		const specificity = compound(selector.trim(), theme);
		if (specificity !== null) best = Math.max(best ?? 0, specificity);
	}
	return best;
}

function compound(selector: string, theme: string): number | null {
	let rest = selector;
	let specificity = 0;
	while (rest) {
		const pseudo = /^:(where|is)\(/.exec(rest);
		if (pseudo) {
			const end = closingParen(rest, pseudo[0].length - 1);
			const inner = selectorList(rest.slice(pseudo[0].length, end), theme);
			if (inner === null) return null;
			if (pseudo[1] === "is") specificity += inner;
			rest = rest.slice(end + 1);
			continue;
		}
		const attribute = /^\[data-theme(?:="([^"]*)")?\]/.exec(rest);
		const simple = attribute ?? /^:root/.exec(rest);
		if (simple) {
			if (attribute?.[1] !== undefined && attribute[1] !== theme) return null;
			specificity += 100;
		} else if (/^html(?![\w-])/.test(rest)) specificity += 1;
		else return null;
		rest = rest.slice(simple ? simple[0].length : 4);
	}
	return specificity;
}

function closingParen(text: string, open: number): number {
	let depth = 0;
	for (let index = open; index < text.length; index++) {
		if (text[index] === "(") depth++;
		else if (text[index] === ")" && --depth === 0) return index;
	}
	throw new Error(`Unbalanced parentheses: ${text}`);
}

function splitTopLevel(text: string, separator: string): string[] {
	const parts: string[] = [];
	let depth = 0;
	let start = 0;
	for (let index = 0; index < text.length; index++) {
		const char = text[index];
		if (char === "(") depth++;
		else if (char === ")") depth--;
		else if (char === separator && depth === 0) {
			parts.push(text.slice(start, index));
			start = index + 1;
		}
	}
	return [...parts, text.slice(start)];
}

function substitute(
	value: string,
	properties: Map<string, string>,
	seen: ReadonlySet<string>,
): string | null {
	const start = value.indexOf("var(");
	if (start < 0) return value;
	const end = closingParen(value, start + 3);
	const [name = "", ...fallback] = splitTopLevel(
		value.slice(start + 4, end),
		",",
	);
	const property = name.trim();
	const declared = seen.has(property) ? undefined : properties.get(property);
	const replacement =
		declared !== undefined
			? substitute(declared.trim(), properties, new Set([...seen, property]))
			: fallback.length
				? substitute(fallback.join(",").trim(), properties, seen)
				: null;
	if (replacement === null) return null;
	return substitute(
		value.slice(0, start) + replacement + value.slice(end + 1),
		properties,
		seen,
	);
}

function parseRgba(value: string): [number, number, number, number] | null {
	if (!value) return null;
	const node = parseComponentValue(
		tokenize({ css: `color-mix(in srgb, ${value} 100%, transparent 0%)` }),
	);
	const data = node && parseColor(node);
	if (!data || typeof data.alpha !== "number") return null;
	const [r, g, b] = data.channels.map(
		(channel) => Math.min(1, Math.max(0, channel)) * 255,
	);
	return [r ?? 0, g ?? 0, b ?? 0, data.alpha];
}

export function stylesheetTokenSource(theme: string): BoardThemeTokenSource {
	const properties = rootProperties(theme);
	const token = (name: string) => {
		const declared = properties.get(name);
		if (declared === undefined) return "";
		return (
			substitute(declared.trim(), properties, new Set([name]))?.trim() ?? ""
		);
	};
	return {
		token,
		color(name, backdrop) {
			const rgba = parseRgba(token(name));
			if (!rgba) return null;
			const alpha = backdrop === undefined ? 1 : rgba[3];
			const channel = (index: number) => {
				const under = ((backdrop ?? 0) >> (16 - index * 8)) & 0xff;
				return Math.round((rgba[index] ?? 0) * alpha + under * (1 - alpha));
			};
			return (channel(0) << 16) | (channel(1) << 8) | channel(2);
		},
	};
}

export function resolveBuiltinBoardThemes() {
	return Object.fromEntries(
		RESOLVED_THEMES.map((theme) => {
			const source = stylesheetTokenSource(theme);
			const { palette, colors } = readBoardThemeColors(source);
			return [
				theme,
				{
					colorScheme: isDarkTheme(theme) ? "dark" : "light",
					palette,
					colors,
					style: readBoardThemeStyle(source),
				},
			];
		}),
	);
}

const COLOR_KEYS = new Set(["palette", "colors", "color"]);

function literal(value: unknown, indent = "", color = false): string {
	if (typeof value === "number")
		return color ? `0x${value.toString(16).padStart(6, "0")}` : String(value);
	if (typeof value !== "object" || value === null) return JSON.stringify(value);
	const key = (name: string) =>
		/^[a-z]\w*$/i.test(name) ? name : JSON.stringify(name);
	const entries = Object.entries(value).map(
		([name, entry]) =>
			[
				key(name),
				literal(entry, `${indent}\t`, color || COLOR_KEYS.has(name)),
			] as const,
	);
	if (!entries.length) return "{}";
	if (
		entries.every(([, text]) => !text.includes("\n")) &&
		Object.values(value).every((entry) => typeof entry !== "object")
	)
		return `{ ${entries.map(([name, text]) => `${name}: ${text}`).join(", ")} }`;
	return `{\n${entries.map(([name, text]) => `${indent}\t${name}: ${text},`).join("\n")}\n${indent}}`;
}

export function render(): string {
	return [
		HEADER,
		"",
		`export const BOARD_THEME_IDS = ${JSON.stringify(RESOLVED_THEMES).replaceAll(",", ", ")} as const;`,
		"",
		"export type BoardThemeId = (typeof BOARD_THEME_IDS)[number];",
		"",
		`export const BOARD_THEME_DATA = ${literal(resolveBuiltinBoardThemes())} as const;`,
		"",
	].join("\n");
}

export function stale(): boolean {
	let current = "";
	try {
		current = readFileSync(GENERATED, "utf8");
	} catch {}
	return current !== render();
}

if (process.argv[1] === fileURLToPath(import.meta.url))
	writeFileSync(GENERATED, render());
