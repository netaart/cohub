import { writeFile } from "node:fs/promises";
import { loadEnv } from "vite";

// Emits `#worker-entry-deps`, the module `src/entry.worker.ts` imports.
//
// The entry runs before the SvelteKit handler and is bundled by Wrangler, which
// resolves neither SvelteKit's `$env` aliases nor Vite's `.env` files. Emitting
// one module that re-exports the adapter Worker and the public values keeps a
// single source of truth for them, instead of reintroducing the values as runtime
// Worker variables. `package.json` maps the specifier to this file, and
// `src/entry.worker-deps.d.ts` declares its types for fresh checkouts.
//
// Vite's own `loadEnv` resolves the values, so mode files (`.env.local`,
// `.env.production`, …), quoting and interpolation behave exactly as in the
// build — the build mode defaults to `production`, matching `vite build`.
//
// Runs after `vite build`, which recreates `.svelte-kit/cloudflare`, so this file
// is always regenerated from the same values as the bundle.

const appDir = new URL("../", import.meta.url);
const outfile = new URL(".svelte-kit/cloudflare/worker-entry-deps.js", appDir);

const NAMES = ["PUBLIC_API_ORIGIN", "PUBLIC_APP_STANDALONE_HOST_TEMPLATE"];

const mode = process.argv[2] ?? "production";
const env = {
	...loadEnv(mode, appDir.pathname, "PUBLIC_"),
	// Vite lets existing process env values win over `.env` files.
	...Object.fromEntries(
		NAMES.filter((name) => process.env[name]).map((name) => [
			name,
			process.env[name],
		]),
	),
};

await writeFile(
	outfile,
	[
		"// Generated by scripts/generate-worker-entry-env.mjs. Do not edit.",
		`export { default as adapter } from "./_worker.js";`,
		...NAMES.map(
			(name) => `export const ${name} = ${JSON.stringify(env[name] ?? "")};`,
		),
		"",
	].join("\n"),
);
