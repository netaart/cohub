import { writeFile } from "node:fs/promises";
import { loadEnv } from "vite";

// Emits the build-time public values the Worker entry needs.
//
// `src/entry.worker.ts` runs before the SvelteKit handler and is bundled by
// Wrangler, which resolves neither SvelteKit's `$env` aliases nor Vite's `.env`
// files. Writing a plain module next to the adapter output keeps one source of
// truth for these values instead of reintroducing them as runtime Worker
// variables.
//
// Vite's own `loadEnv` resolves them, so mode files (`.env.local`,
// `.env.production`, …), quoting and interpolation behave exactly as in the
// build — the build mode defaults to `production`, matching `vite build`.
//
// Runs after `vite build`, which recreates `.svelte-kit/cloudflare` on every
// build, so this file is always regenerated from the same values as the bundle.
// It also writes sibling `.d.ts` files: without them TypeScript follows the
// imports into the generated JavaScript and reports its internals (see
// `src/entry.worker.d.ts`).

const appDir = new URL("../", import.meta.url);
const out = (name) => new URL(`.svelte-kit/cloudflare/${name}`, appDir);

const NAMES = ["PUBLIC_API_ORIGIN", "PUBLIC_APP_STANDALONE_HOST_TEMPLATE"];

const mode = process.argv[2] ?? "production";
const env = {
	...loadEnv(mode, appDir.pathname, "PUBLIC_"),
	// Vite lets existing process env values win over `.env` files.
	...Object.fromEntries(
		NAMES.filter((name) => process.env[name]).map((name) => [
			name,
			process.env[name],
		]),
	),
};

await writeFile(
	out("worker-entry-env.js"),
	`// Generated by scripts/generate-worker-entry-env.mjs. Do not edit.\n${NAMES.map(
		(name) => `export const ${name} = ${JSON.stringify(env[name] ?? "")};`,
	).join("\n")}\n`,
);

await writeFile(
	out("worker-entry-env.d.ts"),
	`// Generated by scripts/generate-worker-entry-env.mjs. Do not edit.\n${NAMES.map(
		(name) => `export declare const ${name}: string;`,
	).join("\n")}\n`,
);

// The adapter's Worker is imported for its handler shape and for delegation, so
// it needs a declaration too.
await writeFile(
	out("_worker.d.ts"),
	`// Generated by scripts/generate-worker-entry-env.mjs. Do not edit.\n` +
		`declare const worker: {\n` +
		`\tfetch(request: Request, env: unknown, ctx: unknown): Promise<Response>;\n` +
		`};\n` +
		`export default worker;\n`,
);
