import { readdir, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { loadEnv } from "vite";

// Emits `#worker-entry-deps`, the module `entry.worker.ts` imports.
//
// The entry runs before the SvelteKit handler and is bundled by Wrangler, which
// resolves neither SvelteKit's `$env` aliases nor Vite's `.env` files. Emitting
// one module that re-exports the adapter Worker, the public values and the
// generated asset paths keeps a single source of truth for them, instead of
// reintroducing them as runtime Worker variables. `package.json` maps the
// specifier to this file, and `src/entry.worker-deps.d.ts` declares its types
// for fresh checkouts.
//
// Vite's own `loadEnv` resolves the values, so mode files (`.env.local`,
// `.env.production`, …), quoting and interpolation behave exactly as in the
// build — the build mode defaults to `production`, matching `vite build`.
//
// Runs after `vite build`, which recreates `.svelte-kit/cloudflare`, so this file
// is always regenerated from the same values as the bundle.

const appDir = new URL("../", import.meta.url);
const outfile = new URL(".svelte-kit/cloudflare/worker-entry-deps.js", appDir);
const clientDir = new URL(".svelte-kit/output/client/", appDir);
// SvelteKit's `kit.files.assets`; svelte.config.js keeps the default.
const staticDir = new URL("static/", appDir);

const NAMES = ["PUBLIC_API_ORIGIN", "PUBLIC_APP_STANDALONE_HOST_TEMPLATE"];

const mode = process.argv[2] ?? "production";
const env = {
	...loadEnv(mode, appDir.pathname, "PUBLIC_"),
	// Vite lets existing process env values win over `.env` files.
	...Object.fromEntries(
		NAMES.filter((name) => process.env[name]).map((name) => [
			name,
			process.env[name],
		]),
	),
};

/** Relative paths of every file under `dir`, `/`-separated. */
async function listFiles(dir) {
	const root = fileURLToPath(dir);
	const entries = await readdir(root, { recursive: true, withFileTypes: true });
	return entries
		.filter((entry) => entry.isFile())
		.map((entry) =>
			relative(root, join(entry.parentPath, entry.name)).split(sep).join("/"),
		);
}

// With `run_worker_first`, the adapter serves only the static assets it knows
// about: `static/`, prerendered pages and `_app/`. Files Vite plugins emit at
// build time (vite-plugin-pwa's `sw.js`, `workbox-*.js`, `manifest.webmanifest`)
// sit outside its manifest and would 404, so the entry serves them instead.
// Hidden paths (Vite's `.vite/manifest.json`) are build metadata SvelteKit does
// not deploy.
const staticFiles = new Set(await listFiles(staticDir));
const generatedAssetPaths = (await listFiles(clientDir))
	.filter(
		(file) =>
			!file.startsWith("_app/") &&
			!file.split("/").some((segment) => segment.startsWith(".")) &&
			!staticFiles.has(file),
	)
	.map((file) => `/${file}`)
	.sort();

await writeFile(
	outfile,
	[
		"// Generated by scripts/generate-worker-entry-deps.mjs. Do not edit.",
		`export { default as adapter } from "./_worker.js";`,
		...NAMES.map(
			(name) => `export const ${name} = ${JSON.stringify(env[name] ?? "")};`,
		),
		`export const GENERATED_ASSET_PATHS = ${JSON.stringify(generatedAssetPaths)};`,
		"",
	].join("\n"),
);
